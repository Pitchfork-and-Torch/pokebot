import { DEX } from "./dex";
import type { Specimen } from "./types";

function plate(
  spec: Omit<Specimen, "never_list" | "tools" | "rarity" | "risk" | "origin"> & Partial<Specimen>,
): Specimen {
  return {
    never_list: spec.never_list ?? [],
    tools: spec.tools ?? [],
    rarity: spec.rarity ?? "uncommon",
    risk: spec.risk ?? "low",
    origin: spec.origin ?? "wild",
    kind: spec.kind ?? "grok-bot",
    ...spec,
  };
}

