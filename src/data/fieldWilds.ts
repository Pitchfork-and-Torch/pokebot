export const FIELD_DEX_WILDS: Specimen[] = DEX.filter((s) => s.origin === "wild" || s.origin === "duplicate");

export const FIELD_POOL: Specimen[] = [...FIELD_DEX_WILDS, ...FIELD_NEW];

export const FIELD_BY_ID: Record<string, Specimen> = Object.fromEntries(
  [...DEX, ...FIELD_NEW].map((s) => [s.id, s]),
);

export function getFieldPlate(id: string): Specimen | undefined {
  return FIELD_BY_ID[id];
}
